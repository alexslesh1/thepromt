export function staticView(name) {
  return async function render() {
    const main = shell();
    main.replaceChildren();
    mountMobileTop(main);

    const page = PAGES[name];
    main.append(header({ title: page.title, subtitle: page.subtitle, back: true }));

    const article = h('div', { class: 'static-page', style: { marginTop: '18px' } });
    for (const [tag, content] of page.blocks) {
      if (tag === 'ul') {
        article.append(h('ul', {}, content.map((item) => h('li', { text: item }))));
      } else {
        article.append(h(tag, { text: content }));
      }
    }
    main.append(article);
  };
}
