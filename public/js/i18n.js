/** Текущая локаль — что бы ни лежало в state.locale (в т.ч. код, определённый по языку браузера). */
export function currentLocale() {
  return state.locale || 'en';
}

/**
 * Переводит ключ на текущий язык интерфейса. Полный словарь есть не для
 * всех языков из LOCALES (см. FULLY_TRANSLATED_LOCALES) — для остальных
 * это честно откатывается на английский, а не показывает ключ как попало.
 */
export function t(key) {
  const locale = currentLocale();
  return DICT[locale]?.[key] ?? DICT.en[key] ?? DICT.ru[key] ?? key;
}

