/** Подменяет label/short/hint модели на переведённые, если для текущей локали есть таблица. */
export function translateModel(model) {
  if (!model) return model;
  const found = MODEL_LABELS[currentLocale()]?.[model.id];
  return found ? { ...model, ...found } : model;
}

const pick = (table, id, fallback) => table[currentLocale()]?.[id] ?? fallback;

export const translateDifficulty = (id, fallback) => pick(DIFFICULTY_LABELS, id, fallback);
export const translateCategory = (id, fallback) => pick(CATEGORY_LABELS, id, fallback);
export const translateSort = (id, fallback) => pick(SORT_LABELS, id, fallback);
export const translateReportReason = (id, fallback) => pick(REPORT_REASON_LABELS, id, fallback);
